"""First-run configuration for the BuildShield Docker stack.

Runs inside the `setup` service before the API starts. It:

1. reuses an existing ``.env`` (including a legacy ``services/api/.env``),
2. asks for the GitHub token, repository, webhook secret and admin account,
3. writes ``.env`` at the repository root, which the API sources at boot,
4. creates the first admin account,
5. registers the GitHub webhook when a token and a public URL are available.

Re-running with a complete ``.env`` only prints a summary, so ``docker compose
up`` stays a no-op after the first configuration. Prompts are bounded by a
timeout so a detached ``docker compose up -d`` can never hang.
"""

from __future__ import annotations

import argparse
import asyncio
import os
import re
import secrets
import string
import sys
from pathlib import Path
from typing import Dict, Optional, Tuple

PROJECT_DIR = Path(os.getenv("BUILDSHIELD_PROJECT_DIR", "/project"))
ENV_PATH = PROJECT_DIR / ".env"
LEGACY_ENV_PATH = PROJECT_DIR / "services" / "api" / ".env"

MANAGED_KEYS = (
    "SECRET_KEY",
    "GITHUB_WEBHOOK_SECRET",
    "GITHUB_TOKEN",
    "GITHUB_REPOSITORY",
    "PUBLIC_BASE_URL",
    "SMTP_HOST",
    "SMTP_PORT",
    "SMTP_USERNAME",
    "SMTP_PASSWORD",
    "SMTP_FROM",
    "SMTP_SECURITY",
)

LOCAL_HOSTS = {"localhost", "127.0.0.1", "0.0.0.0", "host.docker.internal"}

# Seconds a prompt waits for input before falling back to the default.
PROMPT_TIMEOUT = float(os.getenv("BUILDSHIELD_PROMPT_TIMEOUT", "180"))
GATE_TIMEOUT = float(os.getenv("BUILDSHIELD_GATE_TIMEOUT", "20"))

BANNER = r"""
  ____                  _  ____  _     _      _     _
 | __ ) _   _ _ __   __| |/ ___|| |__ (_) ___| | __| |
 |  _ \| | | | '_ \ / _` |\___ \| '_ \| |/ _ \ |/ _` |
 | |_) | |_| | | | | (_| | ___) | | | | |  __/ | (_| |
 |____/ \__,_|_| |_|\__,_||____/|_| |_|_|\___|_|\__,_|
"""


# --------------------------------------------------------------------------- env


def read_env(path: Path) -> Dict[str, str]:
    values: Dict[str, str] = {}
    if not path.is_file():
        return values

    for raw in path.read_text(encoding="utf-8", errors="replace").splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        key = key.strip()
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in {'"', "'"}:
            value = value[1:-1]
        if key:
            values[key] = value
    return values


def quote(value: str) -> str:
    """Quotes a value so `sh` can source the file safely."""
    if value == "":
        return ""
    if re.search(r"[\s#\"'`$\\]", value):
        escaped = (
            value.replace("\\", "\\\\")
            .replace('"', '\\"')
            .replace("$", "\\$")
            .replace("`", "\\`")
        )
        return f'"{escaped}"'
    return value


def write_env(values: Dict[str, str]) -> Path:
    lines = [
        "# BuildShield configuration.",
        "# Generated by the setup wizard; change it with:",
        "#   docker compose run --rm -e BUILDSHIELD_RECONFIGURE=1 setup",
        "# Never commit this file.",
        "",
    ]
    for key in MANAGED_KEYS:
        if values.get(key):
            lines.append(f"{key}={quote(values[key])}")

    # Keys starting with "_" are runtime-only (admin password) and never written.
    extras = {
        key: value
        for key, value in values.items()
        if key not in MANAGED_KEYS and value and not key.startswith("_")
    }
    if extras:
        lines.append("")
        for key in sorted(extras):
            lines.append(f"{key}={quote(extras[key])}")

    ENV_PATH.parent.mkdir(parents=True, exist_ok=True)
    ENV_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")
    try:
        os.chmod(ENV_PATH, 0o600)
    except OSError:
        pass  # Windows bind mounts do not carry POSIX modes.
    return ENV_PATH


def is_complete(values: Dict[str, str]) -> bool:
    return bool(values.get("SECRET_KEY")) and bool(values.get("GITHUB_WEBHOOK_SECRET"))


def mask(value: str) -> str:
    if not value:
        return "(unset)"
    if len(value) <= 8:
        return value[:2] + "..."
    return f"{value[:6]}...{value[-4:]}"


# ------------------------------------------------------------------------ values


def new_secret() -> str:
    return secrets.token_hex(32)


def new_webhook_secret() -> str:
    return secrets.token_urlsafe(32)


def new_password(length: int = 16) -> str:
    alphabet = string.ascii_letters + string.digits
    while True:
        candidate = "".join(secrets.choice(alphabet) for _ in range(length))
        if (
            any(c.islower() for c in candidate)
            and any(c.isupper() for c in candidate)
            and any(c.isdigit() for c in candidate)
        ):
            return candidate


def is_local_base(url: str) -> bool:
    from urllib.parse import urlparse

    host = (urlparse(url).hostname or "").lower()
    return host in LOCAL_HOSTS


# ----------------------------------------------------------------------- prompts


def _read_line(prompt: str, timeout: Optional[float], secret: bool = False) -> Tuple[str, bool]:
    """Reads one line, hiding echo for secrets.

    Returns (text, saw_input). On timeout or EOF it returns ("", False) instead
    of blocking, which keeps an unattended `docker compose up -d` from hanging.
    """
    print(prompt, end="", flush=True)

    fd = None
    saved = None
    try:
        import select
        import termios

        fd = sys.stdin.fileno()
        if secret:
            saved = termios.tcgetattr(fd)
            hidden = termios.tcgetattr(fd)
            hidden[3] &= ~termios.ECHO
            termios.tcsetattr(fd, termios.TCSADRAIN, hidden)

        ready, _, _ = select.select([sys.stdin], [], [], timeout)
        if not ready:
            if secret:
                print()
            print("(no input - using the default)")
            return "", False

        line = sys.stdin.readline()
        if secret:
            print()
        if line == "":
            return "", False
        return line.rstrip("\r\n"), True
    except Exception:
        try:
            return input().strip(), True
        except (EOFError, KeyboardInterrupt):
            print()
            return "", False
    finally:
        if fd is not None and saved is not None:
            try:
                import termios

                termios.tcsetattr(fd, termios.TCSADRAIN, saved)
            except Exception:
                pass


def ask(question: str, default: Optional[str] = None, secret: bool = False) -> str:
    suffix = f" [{default}]" if default else ""
    answer, saw_input = _read_line(f"{question}{suffix}: ", PROMPT_TIMEOUT, secret=secret)
    answer = answer.strip()
    if not saw_input:
        return default or ""
    return answer or (default or "")


def print_github_token_steps() -> None:
    print(
        "\nHow to create a GitHub token:\n"
        "  1. Open https://github.com/settings/tokens\n"
        "  2. Generate new token (classic)\n"
        "  3. Select scopes: repo (read code) and admin:repo_hook (so setup can add the webhook)\n"
        "  4. Copy the token (it starts with ghp_); GitHub shows it only once.\n"
        "  Fine-grained tokens also work: Contents: Read, Webhooks: Read and write.\n"
        "  Leave the token blank to skip GitHub integration for now.\n"
    )


def print_webhook_steps(base_url: str, secret: str) -> None:
    payload = base_url.rstrip("/") + "/api/v1/webhooks/github"
    print(
        "\nAdd the webhook in GitHub:\n"
        "  1. Repository -> Settings -> Webhooks -> Add webhook\n"
        f"  2. Payload URL:  {payload}\n"
        "  3. Content type: application/json\n"
        f"  4. Secret:       {secret}\n"
        "  5. Events:       Pull requests and Pushes\n"
        "  6. Save. GitHub sends a ping; BuildShield answers \"pong\".\n"
        "\nGitHub cannot reach localhost: for local testing expose the API with a\n"
        "tunnel (for example `ngrok http 8000`) and use that public URL.\n"
    )


# ------------------------------------------------------------------------- admin


async def prepare_database() -> None:
    """Brings the schema up to date before the API starts.

    Alembic only ships the original migration, while the models have grown since;
    the API normally reconciles that with ``create_all`` in its lifespan. Setup runs
    first, so it performs the same step or the admin insert hits missing columns.
    """
    from app.database import Base, engine
    from app.migrations import ensure_schema

    import app.models  # noqa: F401  (registers every table on Base.metadata)

    async with engine.begin() as conn:
        await conn.run_sync(Base.metadata.create_all)
        await ensure_schema(conn)


async def ensure_admin(username: str, email: str, password: str) -> str:
    """Creates the first account when the database has none."""
    try:
        from sqlalchemy.future import select

        from app.auth import get_password_hash
        from app.database import SessionLocal
        from app.models import User, WorkspaceMember
    except Exception as error:  # pragma: no cover - misconfigured environment
        print(f"! Could not load the application models: {error}")
        return "error"

    try:
        await prepare_database()
    except Exception as error:
        print(f"! Could not prepare the database ({error}); the API will retry at startup.")

    try:
        async with SessionLocal() as db:
            existing = (await db.execute(select(User).limit(1))).scalars().first()
            if existing is not None:
                print(f"i An account already exists ({existing.username}); keeping it.")
                return "exists"

            if not password:
                password = new_password()
                print(f"+ Admin password: {password}   <-- shown once")

            user = User(
                username=username,
                email=email,
                hashed_password=get_password_hash(password),
            )
            db.add(user)
            await db.commit()
            await db.refresh(user)

            member = (
                await db.execute(select(WorkspaceMember).where(WorkspaceMember.email == email))
            ).scalars().first()
            if member is None:
                db.add(
                    WorkspaceMember(user_id=user.id, email=email, role="owner", status="active")
                )
                await db.commit()

            print(f"+ Created admin account {username} <{email}>")
            return "created"
    except Exception as error:
        print(f"! Could not create the admin account yet ({error}).")
        print("  The API still starts; create the account from the sign-in screen.")
        return "error"


# ----------------------------------------------------------------------- webhook


def configure_webhook(token: str, repository: str, secret: str, base_url: str) -> str:
    """Registers the webhook through the GitHub API."""
    if not token or not repository:
        return "skipped"

    payload_url = base_url.rstrip("/") + "/api/v1/webhooks/github"
    if is_local_base(base_url):
        return "local"

    try:
        import httpx
    except Exception:
        return "error"

    headers = {
        "Authorization": f"Bearer {token}",
        "Accept": "application/vnd.github+json",
        "X-GitHub-Api-Version": "2022-11-28",
        "User-Agent": "BuildShield-Setup",
    }
    api = f"https://api.github.com/repos/{repository.strip().strip('/')}"

    try:
        with httpx.Client(timeout=20.0, headers=headers) as client:
            listed = client.get(f"{api}/hooks")
            if listed.status_code == 404:
                print(f"! Repository '{repository}' was not found, or the token cannot read it.")
                return "error"
            if listed.status_code == 401:
                print("! GitHub rejected the token. Check that it is valid and has the repo scope.")
                return "error"
            if listed.status_code >= 400:
                print(f"! GitHub returned {listed.status_code} while listing webhooks.")
                return "error"

            for hook in listed.json():
                config = hook.get("config") or {}
                if config.get("url") == payload_url:
                    print(f"i Webhook already points at {payload_url}; left unchanged.")
                    return "exists"

            created = client.post(
                f"{api}/hooks",
                json={
                    "name": "web",
                    "active": True,
                    "events": ["push", "pull_request"],
                    "config": {
                        "url": payload_url,
                        "content_type": "json",
                        "secret": secret,
                        "insecure_ssl": "0",
                    },
                },
            )
            if created.status_code in (200, 201):
                print(f"+ GitHub webhook created: {payload_url}")
                return "created"

            message = ""
            try:
                message = created.json().get("message", "")
            except Exception:
                pass
            print(f"! Could not create the webhook (HTTP {created.status_code}). {message}".strip())
            return "error"
    except Exception as error:
        print(f"! Webhook setup failed: {error}")
        return "error"


# -------------------------------------------------------------------------- main


def parse_args(argv: Optional[list] = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="BuildShield first-run setup")
    parser.add_argument("--non-interactive", action="store_true")
    parser.add_argument("--reconfigure", action="store_true")
    parser.add_argument("--skip-admin", action="store_true")
    parser.add_argument("--skip-webhook", action="store_true")
    return parser.parse_args(argv)


def gather_values(existing: Dict[str, str], args: argparse.Namespace) -> Dict[str, str]:
    values: Dict[str, str] = dict(existing)
    values.setdefault("SECRET_KEY", "")
    values.setdefault("GITHUB_WEBHOOK_SECRET", "")

    if not values["SECRET_KEY"]:
        values["SECRET_KEY"] = new_secret()
    if not values["GITHUB_WEBHOOK_SECRET"]:
        values["GITHUB_WEBHOOK_SECRET"] = new_webhook_secret()

    print_github_token_steps()
    values["GITHUB_TOKEN"] = ask(
        "GitHub personal access token (blank to skip)", values.get("GITHUB_TOKEN", ""), secret=True
    )

    repository = ""
    if values["GITHUB_TOKEN"]:
        repository = ask(
            "Repository for the webhook (owner/name, blank to skip)",
            values.get("GITHUB_REPOSITORY", ""),
        )
    values["GITHUB_REPOSITORY"] = repository

    base_url = ask(
        "Public URL GitHub should call (blank for localhost)",
        values.get("PUBLIC_BASE_URL", "http://localhost:8000"),
    )
    values["PUBLIC_BASE_URL"] = base_url or "http://localhost:8000"

    print(f"\nWebhook signing secret: {values['GITHUB_WEBHOOK_SECRET']}")
    override = ask("Press Enter to keep it, or type your own", "", secret=True)
    if override:
        values["GITHUB_WEBHOOK_SECRET"] = override

    print("\nAdmin account (used for the first sign-in):")
    values["_ADMIN_USERNAME"] = ask("Username", "admin")
    values["_ADMIN_EMAIL"] = ask("Email", "admin@buildshield.local")
    password = ask("Password (blank generates one)", "", secret=True)
    if not password:
        password = new_password()
        print(f"  Generated password: {password}")
    values["_ADMIN_PASSWORD"] = password

    print(
        "\nOptional email delivery. Leave blank to keep the bundled MailHog inbox\n"
        "(web UI at http://localhost:8025)."
    )
    smtp_host = ask("SMTP host", values.get("SMTP_HOST", ""))
    if smtp_host:
        values["SMTP_HOST"] = smtp_host
        values["SMTP_PORT"] = ask("SMTP port", values.get("SMTP_PORT", "587"))
        values["SMTP_USERNAME"] = ask("SMTP username", values.get("SMTP_USERNAME", ""))
        smtp_password = ask("SMTP password", values.get("SMTP_PASSWORD", ""), secret=True)
        if smtp_password:
            values["SMTP_PASSWORD"] = smtp_password
        values["SMTP_SECURITY"] = ask(
            "SMTP security (starttls/ssl/none)", values.get("SMTP_SECURITY", "starttls")
        )
        values["SMTP_FROM"] = ask(
            "From address", values.get("SMTP_FROM", "no-reply@buildshield.local")
        )

    return values


def defaults_without_prompt(existing: Dict[str, str]) -> Dict[str, str]:
    values: Dict[str, str] = dict(existing)
    values.setdefault("SECRET_KEY", new_secret())
    values.setdefault("GITHUB_WEBHOOK_SECRET", new_webhook_secret())
    values.setdefault("PUBLIC_BASE_URL", os.getenv("PUBLIC_BASE_URL", "http://localhost:8000"))
    values.setdefault("GITHUB_TOKEN", os.getenv("GITHUB_TOKEN", ""))
    values.setdefault("GITHUB_REPOSITORY", os.getenv("GITHUB_REPOSITORY", ""))

    values["_ADMIN_USERNAME"] = os.getenv("BUILDSHIELD_ADMIN_USERNAME", "admin")
    values["_ADMIN_EMAIL"] = os.getenv("BUILDSHIELD_ADMIN_EMAIL", "admin@buildshield.local")
    # Generated by ensure_admin only if the database is actually empty.
    values["_ADMIN_PASSWORD"] = os.getenv("BUILDSHIELD_ADMIN_PASSWORD", "")
    return values


def print_summary(values: Dict[str, str], admin_status: str, webhook_status: str) -> None:
    web_port = os.getenv("WEB_PORT", "3000")
    api_port = os.getenv("API_PORT", "8000")
    base = values.get("PUBLIC_BASE_URL", "http://localhost:8000")

    print("\n" + "=" * 70)
    print(" BuildShield configuration")
    print("=" * 70)
    print(f"  Dashboard         http://localhost:{web_port}")
    print(f"  API docs          http://localhost:{api_port}/docs")
    print(f"  Mail inbox        http://localhost:8025")
    print(f"  Webhook endpoint  {base.rstrip('/')}/api/v1/webhooks/github")
    print(f"  Config file       {ENV_PATH}")
    print(f"  GitHub token      {mask(values.get('GITHUB_TOKEN', ''))}")
    print(f"  Webhook secret    {mask(values.get('GITHUB_WEBHOOK_SECRET', ''))}")
    print(f"  Webhook setup     {webhook_status}")

    if admin_status == "created":
        print(
            f"  Admin account     {values.get('_ADMIN_USERNAME')} / "
            f"{values.get('_ADMIN_EMAIL')}"
        )
        if values.get("_ADMIN_PASSWORD"):
            print(f"  Admin password    {values.get('_ADMIN_PASSWORD')}   <-- shown once")
    else:
        print(f"  Admin account     {admin_status}")

    if not values.get("GITHUB_TOKEN"):
        print(
            "\n  No GitHub token stored yet. Add one later in Settings -> GitHub\n"
            "  Integration, or re-run the wizard with BUILDSHIELD_RECONFIGURE=1."
        )

    if webhook_status in {"skipped", "local"}:
        print_webhook_steps(base, values.get("GITHUB_WEBHOOK_SECRET", ""))

    print("=" * 70 + "\n")


def main(argv: Optional[list] = None) -> int:
    args = parse_args(argv)
    print(BANNER)

    existing = read_env(ENV_PATH)
    if not existing and LEGACY_ENV_PATH.is_file():
        legacy = read_env(LEGACY_ENV_PATH)
        print("i Importing existing values from services/api/.env")
        if legacy.get("JWT_SECRET") and not legacy.get("SECRET_KEY"):
            legacy["SECRET_KEY"] = legacy["JWT_SECRET"]
        # Compose owns the database URL; a stale host path would break the container.
        legacy.pop("DATABASE_URL", None)
        legacy.pop("JWT_SECRET", None)
        existing = legacy

    reconfigure = args.reconfigure or os.getenv("BUILDSHIELD_RECONFIGURE", "").lower() in {
        "1",
        "true",
        "yes",
    }
    # Values can be complete while the root .env is still missing (legacy import),
    # in which case they must be written before the API starts.
    complete = is_complete(existing) and ENV_PATH.is_file()

    if complete and not reconfigure:
        print("i Configuration already present; leaving it unchanged.")
        print("  Change it with: docker compose run --rm -e BUILDSHIELD_RECONFIGURE=1 setup")
        print_summary(existing, "unchanged", "unchanged")
        return 0

    forced_non_interactive = args.non_interactive or os.getenv(
        "BUILDSHIELD_NONINTERACTIVE", ""
    ).lower() in {"1", "true", "yes"}

    interactive = sys.stdin.isatty() and not forced_non_interactive
    if interactive:
        print("Press Enter to configure GitHub, the webhook and the admin account.")
        print(f"Without input the wizard continues with safe defaults after {int(GATE_TIMEOUT)}s.\n")
        _, saw_input = _read_line("> ", GATE_TIMEOUT)
        interactive = saw_input

    if interactive:
        values = gather_values(existing, args)
    else:
        print("i Running without prompts; generating secure defaults.")
        print("  To be prompted later: docker compose run --rm -e BUILDSHIELD_RECONFIGURE=1 setup\n")
        values = defaults_without_prompt(existing)

    path = write_env(values)
    print(f"+ Wrote {path}")

    admin_status = "skipped"
    if not args.skip_admin:
        admin_status = asyncio.run(
            ensure_admin(
                values.get("_ADMIN_USERNAME", "admin"),
                values.get("_ADMIN_EMAIL", "admin@buildshield.local"),
                values.get("_ADMIN_PASSWORD", ""),
            )
        )

    webhook_status = "skipped"
    if not args.skip_webhook:
        webhook_status = configure_webhook(
            values.get("GITHUB_TOKEN", ""),
            values.get("GITHUB_REPOSITORY", ""),
            values.get("GITHUB_WEBHOOK_SECRET", ""),
            values.get("PUBLIC_BASE_URL", "http://localhost:8000"),
        )

    print_summary(values, admin_status, webhook_status)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
